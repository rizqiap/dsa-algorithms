#include <iostream>
#include <cmath>

using namespace std;

int main() {
    cout << max(5, 10) << "\n"; // can be use to find the highest value
    cout << min(5, 10) << "\n"; // can be use to find the lowest value
    cout << sqrt(64) << "\n"; // square root
    cout << round(2.6) << "\n"; // pembulatan
    cout << log(2) << "\n"; // logaritma

    return 0;
}